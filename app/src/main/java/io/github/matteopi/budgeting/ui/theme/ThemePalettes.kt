/**
 * The hand-tuned palettes for every [AppTheme] except [AppTheme.DYNAMIC] (which takes its colours
 * from the wallpaper on Android 12+ and falls back to Paper below that). Values are raw
 * `0xAARRGGBB` longs so JVM unit tests can check contrast without Android (see `ThemePalettesTest`).
 *
 * The design is deliberately minimalist: near-neutral surfaces, one restrained accent, containers
