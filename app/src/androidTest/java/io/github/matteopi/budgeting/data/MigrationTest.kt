            db.foodDao().deleteAllRecipeLines()
            db.foodDao().deleteIngredient(1)
            assertTrue(db.foodDao().getOwnedItems().isEmpty(), "deleting the ingredient deletes what is owned")
        } finally {
            db.close()
        }
    }

