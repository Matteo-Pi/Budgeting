    /** What `PRAGMA foreign_key_list` says about [table]: (parent table, column, ON DELETE action), sorted. */
    private fun SupportSQLiteDatabase.foreignKeys(table: String): List<Triple<String, String, String>> =
        query("PRAGMA foreign_key_list($table)").use { cursor ->
            val parent = cursor.getColumnIndexOrThrow("table")
            val from = cursor.getColumnIndexOrThrow("from")
            val onDelete = cursor.getColumnIndexOrThrow("on_delete")
            buildList {
                while (cursor.moveToNext()) add(Triple(cursor.getString(parent), cursor.getString(from), cursor.getString(onDelete)))
            }.sortedBy { it.second }
        }

