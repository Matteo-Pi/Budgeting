    fun theVersion4FileOpensWithTheRealDatabaseClassAndKeepsTheFoodRows() = runBlocking<Unit> {
        createVersion3Database()
        helper.runMigrationsAndValidate(DB_NAME, 4, true).close()

        val db = Room.databaseBuilder(context, BudgetDatabase::class.java, DB_NAME).build()
        try {
            val honey = db.foodDao().getIngredient(1)?.toModel()
            assertEquals("Clear honey", honey?.name)
            assertNull(honey?.per100?.addedSugars)
            assertNull(honey?.foodGroup)
            assertEquals(82.4, honey?.per100?.sugars)
            assertEquals(1, db.foodDao().observeRecipes().first().size)

            db.foodDao().upsertOwnedItem(OwnedItem(1, 340.0, 9_000).toEntity())
