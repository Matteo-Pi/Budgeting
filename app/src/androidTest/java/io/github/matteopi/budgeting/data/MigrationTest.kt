    @Test
    fun theVersion3FileOpensWithTheRealDatabaseClassAndKeepsEarlierDataBesideFoodRows() = runBlocking<Unit> {
        createVersion2Database()
        helper.runMigrationsAndValidate(DB_NAME, 3, true).close()

        val db = Room.databaseBuilder(context, BudgetDatabase::class.java, DB_NAME).build()
        try {
            assertEquals(listOf(1L, 2L), db.transactionDao().observeAll().first().map { it.id }.sorted())
            assertEquals(listOf(2L), db.transactionDao().observeAll().first().filter { it.receiptId == 1L }.map { it.id })
            assertEquals(1, db.receiptDao().observeReceipts().first().size)
            assertEquals(listOf(Money(300)), db.receiptDao().observeAllItems().first().map { it.toModel().price })
            assertTrue(db.foodDao().observeIngredients().first().isEmpty())
            assertTrue(db.foodDao().observeRecipes().first().isEmpty())

            // Food rows go through the real DAO, an ingredient linked to the migrated product.
            val milk = Ingredient(
                name = "Semi-skimmed milk", unit = BaseUnit.ML, packSize = 1_136.0, packLabel = "2 pints",
                price = Money(135), priceDate = LocalDate.of(2026, 10, 15), store = "Tesco", productId = 1,
                per100 = Nutrition(kcal = 46.0, protein = 3.6), shelf = Shelf.DAIRY, createdAtEpochMillis = 6_000,
                portions = listOf(Portion("splash", 30.0), Portion("cup", 240.0)),
            )
            val milkId = db.foodDao().saveIngredient(milk.toEntity(), milk.toPortionEntities())
            val porridge = Recipe(
                title = "Porridge", serves = 2, tags = listOf("quick", "breakfast"), createdAtEpochMillis = 7_000, updatedAtEpochMillis = 7_000,
                lines = listOf(RecipeLine(text = "300 ml milk", ingredientId = milkId, quantity = 300.0)),
                steps = listOf(RecipeStep(StepKind.STEP, "Heat", "~5 min", "Heat the milk."), RecipeStep(StepKind.TIP, body = "Stir.")),
            )
            val porridgeId = db.foodDao().saveRecipe(porridge.toEntity(), porridge.toLineEntities(), porridge.toStepEntities())

            assertEquals(
                milk.copy(id = milkId),
                db.foodDao().getIngredient(milkId)?.toModel(),
            )
            assertEquals(
                porridge.copy(id = porridgeId),
                db.foodDao().getRecipe(porridgeId)?.toModel(),
            )

            // A product deleted later clears the ingredient's link instead of failing.
            db.receiptDao().deleteAllProducts()
            assertNull(db.foodDao().getIngredient(milkId)?.ingredient?.productId)
            assertEquals(1, db.receiptDao().observeReceipts().first().size)
        } finally {
            db.close()
        }
    }

